export function getAvailableProperties() {
  return properties.filter((p) => p.status === "available" || p.status === "pending");
}

export function getPubliclyListedProperties() {
  return properties.filter((p) => p.status !== "hidden");
}

export function getFeaturedProperties() {
  return properties.filter((p) => p.featured && (p.status === "available" || p.status === "pending"));
}

export function getSoldProperties() {
  return properties.filter((p) => p.status === "sold");
}

export function getPropertyBySlug(slug: string) {
  return properties.find((p) => p.slug === slug && p.status !== "hidden");
}

export function getAllCounties() {
  return Array.from(new Set(properties.map((p) => p.county))).sort();
}

export function getAllTowns() {
  return Array.from(new Set(properties.map((p) => p.nearestTown))).sort();
}
